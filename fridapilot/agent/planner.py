async def create_plan(
    goal: str,
    target: str = "",
    device: str = "local",
    llm_client: Any = None,
) -> ExecutionPlan:
    """Use LLM to create an execution plan from a natural language goal.

    Args:
        goal: Natural language description of the task.
        target: Target process/package name.
        device: Device type (local/usb/remote).
        llm_client: LiteLLM-compatible client. If None, uses default.

    Returns:
        An ExecutionPlan with concrete steps.
    """
    if llm_client is None:
        from litellm import acompletion
        response = await acompletion(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": PLANNER_SYSTEM_PROMPT},
                {"role": "user", "content": f"Goal: {goal}\nTarget: {target}\nDevice: {device}"},
            ],
            response_format={"type": "json_object"},
            temperature=0.1,
        )
        plan_json = json.loads(response.choices[0].message.content)
    else:
        # Custom LLM client support
        plan_json = await llm_client.plan(goal, target, device)

    return ExecutionPlan(**plan_json)
